// Pre-projects the US states TopoJSON into flat 1920x1080 SVG space so the
// Remotion composition can render a clean 2D map without doing geo math at
// render time. Emits src/map/usaMapData.ts (state fill paths, border mesh,
// and screen coordinates for every city we drop a marker on).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoAlbersUsa, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("us-atlas/states-10m.json");

const WIDTH = 1920;
const HEIGHT = 1080;

const statesFc = feature(topo, topo.objects.states);
const borders = mesh(topo, topo.objects.states, (a, b) => a !== b);

// Fit the whole lower-48 (+AK/HI insets) to our frame with a little padding.
const projection = geoAlbersUsa().fitExtent(
  [
    [40, 40],
    [WIDTH - 40, HEIGHT - 40],
  ],
  statesFc,
);

const path = geoPath(projection);

// geoAlbersUsa returns null for geometry outside the lower-48 + AK/HI clip
// (e.g. territories); drop those so every state path is a real string.
const states = statesFc.features
  .map((f) => ({
    id: String(f.id),
    name: f.properties.name,
    d: path(f),
  }))
  .filter((s) => typeof s.d === "string" && s.d.length > 0);

const bordersPath = path(borders);

// City markers: [name, label, lon, lat]. Order here is only the source list;
// the composition decides reveal order.
const CITIES = {
  batonRouge: { label: "Baton Rouge, LA", lat: 30.4515, lon: -91.1871 },
  biloxi: { label: "Biloxi, MS", lat: 30.396, lon: -88.8853 },
  oceanSprings: { label: "Ocean Springs, MS", lat: 30.4113, lon: -88.8281 },
  galveston: { label: "Galveston, TX", lat: 29.3013, lon: -94.7977 },
  breauxBridge: { label: "Breaux Bridge, LA", lat: 30.2735, lon: -91.8996 },
  robert: { label: "Robert, LA", lat: 30.5646, lon: -90.362 },
  orangeBeach: { label: "Orange Beach, AL", lat: 30.2694, lon: -87.5811 },
  gulfShores: { label: "Gulf Shores, AL", lat: 30.246, lon: -87.7008 },
  mccomb: { label: "McComb, MS", lat: 31.2438, lon: -90.4534 },
  gatlinburg: { label: "Gatlinburg, TN", lat: 35.7143, lon: -83.5102 },
};

const cities = {};
for (const [key, c] of Object.entries(CITIES)) {
  const p = projection([c.lon, c.lat]);
  if (!p) throw new Error(`Projection failed for ${key}`);
  cities[key] = { label: c.label, x: +p[0].toFixed(2), y: +p[1].toFixed(2) };
}

const out = `// AUTO-GENERATED by scripts/generate-map.mjs — do not edit by hand.
// US states projected (geoAlbersUsa) into a flat ${WIDTH}x${HEIGHT} SVG space.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export type MapCity = { label: string; x: number; y: number };

export const STATES: { id: string; name: string; d: string }[] = ${JSON.stringify(
  states,
)};

export const BORDERS_PATH = ${JSON.stringify(bordersPath)};

export const CITIES: Record<string, MapCity> = ${JSON.stringify(cities, null, 2)};
`;

writeFileSync(new URL("../src/map/usaMapData.ts", import.meta.url), out);
console.log(
  `Wrote ${states.length} states, ${Object.keys(cities).length} cities.`,
);
